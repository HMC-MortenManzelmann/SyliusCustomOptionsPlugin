#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${ROOT}"

export HOST_UID="${HOST_UID:-$(id -u)}"
export HOST_GID="${HOST_GID:-$(id -g)}"

XDEBUG_OVERRIDE="${ROOT}/docker/php/xdebug-override.ini"
XDEBUG_ENV="${ROOT}/docker/xdebug.env"

ensure_xdebug_files() {
    if [[ ! -f "${XDEBUG_OVERRIDE}" ]]; then
        printf '%s\n' '; Generated by docker/bin/xdebug. Do not enable Xdebug here by default.' > "${XDEBUG_OVERRIDE}"
    fi
    if [[ ! -f "${XDEBUG_ENV}" ]]; then
        printf '%s\n' 'XDEBUG_MODE=off' > "${XDEBUG_ENV}"
    fi
}

compose() {
    ensure_xdebug_files
    docker compose "$@"
}

run_php() {
    compose run --rm --no-deps=false \
        -e "XDEBUG_MODE=${XDEBUG_MODE:-off}" \
        -e "XDEBUG_CONFIG=${XDEBUG_CONFIG:-}" \
        -e "XDEBUG_SESSION=${XDEBUG_SESSION:-}" \
        php "$@"
}
